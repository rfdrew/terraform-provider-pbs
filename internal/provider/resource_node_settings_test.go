const fakeSubscriptionKey = "pbsc-0123456789"

func TestSubscriptionResourceLifecycle(t *testing.T) {
	h, fake, node := newNodeHarness(t)
	node.shop[fakeSubscriptionKey] = pbsclient.Subscription{Status: "active", ProductName: "Proxmox Backup Server Community Subscription 1 CPU/year",
		RegDate: "2026-01-01 00:00:00", NextDueDate: "2027-01-01"}
	config := h.resourceValue(t, "pbs_subscription", map[string]any{"key": fakeSubscriptionKey})
	inst := h.create(t, "pbs_subscription", config)
	if stringAt(t, inst.state, "status") != "active" || stringAt(t, inst.state, "server_id") != fakeServerID ||
		stringAt(t, inst.state, "check_time") != "2026-11-02T09:00:46Z" || stringAt(t, inst.state, "next_due_date") != "2027-01-01" {
		t.Fatalf("state = %s", inst.state)
	}
	requireEmptyPlan(t, h, inst, config)

	// The daily check changes the status without a plan.
	node.subscription.Status, node.subscription.Message = "invalid", "subscription information too old"
	inst = h.refresh(t, inst)
	requireEmptyPlan(t, h, inst, config)

	// A key PBS knows but Proxmox calls invalid is stored, with a warning.
	other := h.resourceValue(t, "pbs_subscription", map[string]any{"key": "pbsb-abcdef0123"})
	planned := h.plan(t, "pbs_subscription", inst, other)
	requireNoProtocolErrors(t, planned.Diagnostics)
	if !isUnknownAt(t, h.decodeResource(t, "pbs_subscription", planned.PlannedState), "status") {
		t.Fatal("a new key plans the old status")
	}
	applied := h.apply(t, "pbs_subscription", inst, other, planned)
	requireNoProtocolErrors(t, applied.Diagnostics)
	requireProtocolWarningContaining(t, applied.Diagnostics, "Invalid license key")
	inst = &resourceInstance{typeName: "pbs_subscription", state: h.decodeResource(t, "pbs_subscription", applied.NewState), identity: applied.NewIdentity}

	// A key changed outside Terraform shows.
	node.subscription.Key = "pbsp-9999999999"
	inst = h.refresh(t, inst)
	if stringAt(t, inst.state, "key") != "pbsp-9999999999" {
		t.Fatalf("refreshed state = %s", inst.state)
	}

	// Without Sys.Audit on /, PBS does not say: the key stays, with a warning.
	node.noAudit = true
	read := h.read(t, inst)
	requireNoProtocolErrors(t, read.Diagnostics)
	requireProtocolWarningContaining(t, read.Diagnostics, "Sys.Audit on /")
	node.noAudit = false

	h.destroy(t, inst)
	if node.subscription != nil || fake.count("DELETE /nodes/localhost/subscription") != 1 {
		t.Fatal("the subscription is still there")
	}
	// Gone already: destroying again is no error, and a refresh drops it.
	h.destroy(t, inst)
	if refreshed := h.refresh(t, inst); !refreshed.state.IsNull() {
		t.Fatalf("refresh kept a removed subscription: %s", refreshed.state)
	}
}

func TestSubscriptionResourceShopUnreachable(t *testing.T) {
	h, _, node := newNodeHarness(t)
	node.shopDown = true
	config := h.resourceValue(t, "pbs_subscription", map[string]any{"key": fakeSubscriptionKey})
	planned := h.plan(t, "pbs_subscription", nil, config)
	applied := h.apply(t, "pbs_subscription", nil, config, planned)
	requireProtocolErrorContaining(t, applied.Diagnostics, "shop.proxmox.com")
	requireProtocolErrorContaining(t, applied.Diagnostics, "http_proxy of pbs_node_config")
	if node.subscription != nil {
		t.Fatal("a failed check stored the key")
	}
	requireProtocolErrorContaining(t, h.validateResource(t, "pbs_subscription",
		h.resourceValue(t, "pbs_subscription", map[string]any{"key": "pbsc-0123"})), "subscription key")
	requireProtocolErrorContaining(t, h.validateResource(t, "pbs_subscription",
		h.resourceValue(t, "pbs_subscription", map[string]any{"key": "PBSC-0123456789"})), "subscription key")
	requireNoProtocolErrors(t, h.validateResource(t, "pbs_subscription",
		h.resourceValue(t, "pbs_subscription", map[string]any{"key": "pbss-arm-0123456789"})))
}

// The node holding the key already, and active, asks nothing of Proxmox.
func TestSubscriptionResourceImport(t *testing.T) {
	h, _, node := newNodeHarness(t)
	resp := h.importResource(t, "pbs_subscription", "localhost", nil)
	requireNoProtocolErrors(t, resp.Diagnostics)
	read := h.read(t, &resourceInstance{typeName: "pbs_subscription", state: h.decodeResource(t, "pbs_subscription", resp.ImportedResources[0].State)})
	if !h.decodeResource(t, "pbs_subscription", read.NewState).IsNull() {
		t.Fatal("a node without a subscription imported one")
	}

	node.shop[fakeSubscriptionKey] = pbsclient.Subscription{Status: "active"}
	node.subscription = &pbsclient.Subscription{Status: "active", Key: fakeSubscriptionKey, ServerID: fakeServerID, CheckTime: node.now}
	inst := h.importByIdentity(t, "pbs_subscription", map[string]any{"node": "localhost"})
	config := h.resourceValue(t, "pbs_subscription", map[string]any{"key": fakeSubscriptionKey})
	requireEmptyPlan(t, h, inst, config)
	h.create(t, "pbs_subscription", config)
	if node.shopCalls != 0 {
		t.Fatal("setting the key the node holds asked Proxmox")
	}
}

