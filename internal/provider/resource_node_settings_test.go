// --- pbs_dns ---------------------------------------------------------------------

func TestDNSResourceLifecycle(t *testing.T) {
	h, fake, node := newNodeHarness(t)
	node.resolvConf = "# Generated by the installer\ndomain example.org\nnameserver 192.0.2.53\nnameserver 192.0.2.54\n" +
		"nameserver 192.0.2.55\noptions edns0\n"

	// Without search, the node's stays; the nameservers it does not list
	// go, with a warning.
	config := h.resourceValue(t, "pbs_dns", map[string]any{"dns1": "2001:db8::53"})
	planned := h.plan(t, "pbs_dns", nil, config)
	requireNoProtocolErrors(t, planned.Diagnostics)
	applied := h.apply(t, "pbs_dns", nil, config, planned)
	requireNoProtocolErrors(t, applied.Diagnostics)
	requireProtocolWarningContaining(t, applied.Diagnostics, "192.0.2.54, 192.0.2.55")
	inst := &resourceInstance{typeName: "pbs_dns", state: h.decodeResource(t, "pbs_dns", applied.NewState), identity: applied.NewIdentity}
	put := fake.lastCall(t, "PUT /nodes/localhost/dns").form
	if put.Get("digest") == "" || put.Has("search") || put.Get("dns1") != "2001:db8::53" || strings.Join(put["delete"], ",") != "dns2,dns3" {
		t.Fatalf("PUT = %v", put)
	}
	if node.resolvConf != "search example.org\nnameserver 2001:db8::53\n# Generated by the installer\noptions edns0" {
		t.Fatalf("resolv.conf = %q", node.resolvConf)
	}
	if stringAt(t, inst.state, "search") != "example.org" || !isNullAt(t, inst.state, "dns2") || stringAt(t, inst.state, "id") != "localhost" {
		t.Fatalf("state = %s", inst.state)
	}
	requireEmptyPlan(t, h, inst, config)

	// A search domain changed outside Terraform is not drift while the
	// configuration leaves it out.
	node.resolvConf = strings.Replace(node.resolvConf, "search example.org", "search example.net", 1)
	inst = h.refresh(t, inst)
	requireEmptyPlan(t, h, inst, config)

	// Setting all of it.
	config = h.resourceValue(t, "pbs_dns", map[string]any{"search": "example.com", "dns1": "192.0.2.1", "dns2": "192.0.2.2", "dns3": "192.0.2.3"})
	inst = h.update(t, inst, config)
	if !strings.HasPrefix(node.resolvConf, "search example.com\nnameserver 192.0.2.1\nnameserver 192.0.2.2\nnameserver 192.0.2.3\n") {
		t.Fatalf("resolv.conf = %q", node.resolvConf)
	}
	requireEmptyPlan(t, h, inst, config)

	// Removing nameservers deletes them; removing search leaves it.
	config = h.resourceValue(t, "pbs_dns", map[string]any{"dns1": "192.0.2.1"})
	inst = h.update(t, inst, config)
	put = fake.lastCall(t, "PUT /nodes/localhost/dns").form
	if put.Has("search") || strings.Join(put["delete"], ",") != "dns2,dns3" {
		t.Fatalf("PUT = %v", put)
	}
	if stringAt(t, inst.state, "search") != "example.com" {
		t.Fatalf("state = %s", inst.state)
	}
	requireEmptyPlan(t, h, inst, config)

	// Destroying leaves the settings.
	puts := fake.count("PUT /nodes/localhost/dns")
	h.destroy(t, inst)
	if fake.count("PUT /nodes/localhost/dns") != puts || !strings.Contains(node.resolvConf, "nameserver 192.0.2.1") {
		t.Fatal("destroying changed the DNS settings")
	}
}

func TestDNSResourceImportAndErrors(t *testing.T) {
	h, _, node := newNodeHarness(t)
	inst := h.importByID(t, "pbs_dns", "localhost")
	config := h.resourceValue(t, "pbs_dns", map[string]any{"search": "example.org", "dns1": "192.0.2.53", "dns2": "192.0.2.54"})
	requireEmptyPlan(t, h, inst, config)
	inst = h.importByIdentity(t, "pbs_dns", map[string]any{"node": "localhost"})
	requireEmptyPlan(t, h, inst, config)

	// Docker mounts /etc/resolv.conf, and PBS cannot replace it.
	node.mounted = true
	changed := h.resourceValue(t, "pbs_dns", map[string]any{"dns1": "192.0.2.1"})
	planned := h.plan(t, "pbs_dns", inst, changed)
	applied := h.apply(t, "pbs_dns", inst, changed, planned)
	requireProtocolErrorContaining(t, applied.Diagnostics, "--dns-search")

	for _, tc := range []struct {
		attrs map[string]any
		want  string
	}{
		{map[string]any{"dns1": "dns.example.org"}, "IPv4 or IPv6"},
		{map[string]any{"dns1": "fe80::1%eth0"}, "IPv4 or IPv6"},
		{map[string]any{"dns1": "fe80::1"}, "link-local"},
		{map[string]any{"dns1": "192.0.2.1", "dns3": "192.0.2.3"}, "dns2"},
		{map[string]any{"dns1": "192.0.2.1", "search": "a.example b.example"}, "domain name"},
		{map[string]any{"search": "example.org"}, "dns1"},
	} {
		requireProtocolErrorContaining(t, h.validateResource(t, "pbs_dns", h.resourceValue(t, "pbs_dns", tc.attrs)), tc.want)
	}
}

// --- pbs_timezone ----------------------------------------------------------------

func TestTimezoneResourceLifecycle(t *testing.T) {
	h, fake, node := newNodeHarness(t)
	config := h.resourceValue(t, "pbs_timezone", map[string]any{"timezone": "Europe/Vienna"})
	inst := h.create(t, "pbs_timezone", config)
	if node.timezone != "Europe/Vienna" || stringAt(t, inst.state, "id") != "localhost" {
		t.Fatalf("zone %q, state %s", node.timezone, inst.state)
	}
	// timedatectl answers with a line break.
	node.timedated = true
	inst = h.refresh(t, inst)
	requireEmptyPlan(t, h, inst, config)

	node.timezone = "UTC"
	inst = h.refresh(t, inst)
	if stringAt(t, inst.state, "timezone") != "UTC" {
		t.Fatalf("refreshed state = %s", inst.state)
	}
	inst = h.update(t, inst, config)
	if node.timezone != "Europe/Vienna" {
		t.Fatalf("zone %q", node.timezone)
	}

	// The zone the node has already is not sent again; destroying leaves it.
	puts := fake.count("PUT /nodes/localhost/time")
	h.update(t, h.importByID(t, "pbs_timezone", "localhost"), config)
	h.destroy(t, inst)
	if fake.count("PUT /nodes/localhost/time") != puts || node.timezone != "Europe/Vienna" {
		t.Fatal("the zone was set again or reset")
	}

	unknown := h.resourceValue(t, "pbs_timezone", map[string]any{"timezone": "US/Eastern"})
	planned := h.plan(t, "pbs_timezone", inst, unknown)
	applied := h.apply(t, "pbs_timezone", inst, unknown, planned)
	requireProtocolErrorContaining(t, applied.Diagnostics, "tzdata-legacy")

	for _, bad := range []string{"../../etc/passwd", "Europe//Vienna", "/UTC", "Europe/Vienna ", "U", "Europe",
		"America/Argentina", "localtime", "leapseconds"} {
		requireProtocolErrorContaining(t, h.validateResource(t, "pbs_timezone",
			h.resourceValue(t, "pbs_timezone", map[string]any{"timezone": bad})), "timezone")
	}
	requireNoProtocolErrors(t, h.validateResource(t, "pbs_timezone",
		h.resourceValue(t, "pbs_timezone", map[string]any{"timezone": "Etc/GMT+5"})))
}

