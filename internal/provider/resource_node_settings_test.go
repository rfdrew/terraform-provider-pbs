// A token that may not read the time zone or the subscription gets an
// error naming what it needs, where there is one.
func TestNodeSettingsExplainMissingPrivileges(t *testing.T) {
	fake := newFakePBS()
	h := newProtocolHarness(t, fake)
	fake.reply("GET /nodes/localhost/dns", http.StatusForbidden, "permission check failed")
	planned := h.plan(t, "pbs_dns", nil, h.resourceValue(t, "pbs_dns", map[string]any{"dns1": "192.0.2.1"}))
	applied := h.apply(t, "pbs_dns", nil, h.resourceValue(t, "pbs_dns", map[string]any{"dns1": "192.0.2.1"}), planned)
	requireProtocolErrorContaining(t, applied.Diagnostics, dnsModifyPrivilege)
	fake.reply("GET /nodes/localhost/subscription", http.StatusForbidden, "permission check failed")
	resp := h.readDataSourceResponse(t, "pbs_subscription", h.dataSourceValue(t, "pbs_subscription", map[string]any{}))
	requireProtocolErrorContaining(t, resp.Diagnostics, "permission check failed")
}
